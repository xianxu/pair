package workbenchshortcut

import (
	"strconv"
	"strings"
)

func RenderLuaGlobalMaps() string {
	var out strings.Builder
	out.WriteString("-- Code generated by go run ./cmd/internal/workbenchshortcut/generatecmd; DO NOT EDIT.\n")
	out.WriteString("return {\n")
	for _, binding := range GlobalBindings() {
		out.WriteString("  [")
		out.WriteString(strconv.Quote(binding.NvimKey))
		out.WriteString("] = { fn = ")
		out.WriteString(strconv.Quote(binding.LuaFunction))
		out.WriteString(", focus = ")
		out.WriteString(strconv.FormatBool(binding.FocusDraft))
		out.WriteString(" },\n")
	}
	out.WriteString("}\n")
	return out.String()
}
