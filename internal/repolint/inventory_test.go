func fixtureGit(t testing.TB) string {
	t.Helper()
	root := t.TempDir()
	for _, args := range [][]string{{"init", "-b", "main"}, {"config", "user.name", "Fixture"}, {"config", "user.email", "fixture@example.invalid"}, {"config", "commit.gpgsign", "false"}, {"config", "branch.main.remote", "."}, {"config", "branch.main.merge", "refs/heads/main"}} {
		if _, err := gitOutput(root, args...); err != nil {
			t.Fatal(err)
		}
	}
	return root
}
func fixtureWrite(t testing.TB, root, name, text string) {
	t.Helper()
	p := filepath.Join(root, filepath.FromSlash(name))
	if err := os.MkdirAll(filepath.Dir(p), 0700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(text), 0600); err != nil {
		t.Fatal(err)
	}
}
func fixtureCommit(t testing.TB, root string) {
	t.Helper()
	for _, args := range [][]string{{"add", "."}, {"commit", "-m", "fixture"}} {
		if _, err := gitOutput(root, args...); err != nil {
			t.Fatal(err)
		}
	}
}

func TestScanTrackedInventory(t *testing.T) {
	root := fixtureGit(t)
	bad := "package p\nimport \"time\"\nfunc TestBad(){time.Sleep(time.Second)}\n"
	for name, source := range map[string]string{"valid.go": "package p\n", "bad_test.go": bad, "workshop/ignored_test.go": bad, "a/testdata/ignored_test.go": bad, "generated_test.go": "// Code generated by fixture. DO NOT EDIT.\n" + bad, "deleted.go": "package p\n"} {
		fixtureWrite(t, root, name, source)
	}
	fixtureCommit(t, root)
	fixtureWrite(t, root, "untracked_test.go", bad)
	if err := os.Remove(filepath.Join(root, "deleted.go")); err != nil {
		t.Fatal(err)
	}
	reads := 0
	findings, sites, count, err := scanTracked(root, func(name string) ([]byte, error) { reads++; return os.ReadFile(name) })
	if err != nil || len(findings) != 1 || findings[0].Path != "bad_test.go" || len(sites) != 1 || count != 3 || reads != 4 {
		t.Fatalf("findings=%v sites=%v count=%d reads=%d err=%v", findings, sites, count, reads, err)
	}
	sentinel := errors.New("permission denied")
	if _, _, _, err := scanTracked(root, func(string) ([]byte, error) { return nil, sentinel }); !errors.Is(err, sentinel) {
		t.Fatalf("read error swallowed: %v", err)
	}
	fixtureWrite(t, root, "valid.go", "package ???")
	if _, _, _, err := scanTracked(root, os.ReadFile); err == nil {
		t.Fatal("parse error swallowed")
	}
}

func TestScanTrackedRefusesEmptyAndSleepSuppression(t *testing.T) {
	root := fixtureGit(t)
	if _, _, _, err := scanTracked(root, os.ReadFile); err == nil {
		t.Fatal("empty inventory accepted")
	}
	source := "package p\nimport \"time\"\nfunc TestBad(){\n//lint:allow test-fixed-sleep -- a reason cannot authorize debt\ntime.Sleep(time.Second)\n}\n"
	fixtureWrite(t, root, "bad_test.go", source)
	fixtureCommit(t, root)
	if _, _, _, err := scanTracked(root, os.ReadFile); err == nil || !strings.Contains(err.Error(), "bypasses") {
		t.Fatalf("suppression bypass accepted: %v", err)
	}
}

