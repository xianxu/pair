func TestDebtBaselineRealHistory(t *testing.T) {
	site := SleepSite{Path: "x_test.go", Function: "TestA", Call: "time.Sleep(time.Second)", Ordinal: 1}
	debt := Debt{Version: 1, Sites: []SleepSite{site}}
	root := fixtureGit(t)
	data, _ := json.Marshal(debt)
	fixtureWrite(t, root, debtPath, string(data))
	fixtureCommit(t, root)
	if _, err := gitOutput(root, "switch", "-c", "candidate"); err != nil {
		t.Fatal(err)
	}
	fixtureWrite(t, root, debtPath, `{"version":1,"sites":[]}`)
	fixtureCommit(t, root)
	got, err := debtBaseline(root)
	if err != nil || !reflect.DeepEqual(got, debt) {
		t.Fatalf("candidate replaced main authority: %+v %v", got, err)
	}
	if _, err := gitOutput(root, "config", "branch.main.merge", "refs/heads/missing"); err != nil {
		t.Fatal(err)
	}
	if _, err := debtBaseline(root); err == nil {
		t.Fatal("missing main ref accepted")
	}
}

