func fixtureGit(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	for _, args := range [][]string{{"init", "-b", "main"}, {"config", "user.name", "Fixture"}, {"config", "user.email", "fixture@example.invalid"}, {"config", "commit.gpgsign", "false"}, {"config", "branch.main.remote", "."}, {"config", "branch.main.merge", "refs/heads/main"}} {
		if _, err := gitOutput(root, args...); err != nil {
			t.Fatal(err)
		}
	}
	return root
}
func fixtureWrite(t *testing.T, root, name, text string) {
	t.Helper()
	p := filepath.Join(root, filepath.FromSlash(name))
	if err := os.MkdirAll(filepath.Dir(p), 0700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(text), 0600); err != nil {
		t.Fatal(err)
	}
}
func fixtureCommit(t *testing.T, root string) {
	t.Helper()
	for _, args := range [][]string{{"add", "."}, {"commit", "-m", "fixture"}} {
		if _, err := gitOutput(root, args...); err != nil {
			t.Fatal(err)
		}
	}
}

func TestScanTrackedInventory(t *testing.T) {
	root := fixtureGit(t)
	bad := "package p\nimport \"time\"\nfunc TestBad(){time.Sleep(time.Second)}\n"
	for name, source := range map[string]string{"valid.go": "package p\n", "bad_test.go": bad, "workshop/ignored_test.go": bad, "a/testdata/ignored_test.go": bad, "generated_test.go": "// Code generated by fixture. DO NOT EDIT.\n" + bad, "deleted.go": "package p\n"} {
		fixtureWrite(t, root, name, source)
	}
	fixtureCommit(t, root)
	fixtureWrite(t, root, "untracked_test.go", bad)
	if err := os.Remove(filepath.Join(root, "deleted.go")); err != nil {
		t.Fatal(err)
	}
	reads := 0
	findings, sites, count, err := scanTracked(root, func(name string) ([]byte, error) { reads++; return os.ReadFile(name) })
	if err != nil || len(findings) != 1 || findings[0].Path != "bad_test.go" || len(sites) != 1 || count != 3 || reads != 4 {
		t.Fatalf("findings=%v sites=%v count=%d reads=%d err=%v", findings, sites, count, reads, err)
	}
	sentinel := errors.New("permission denied")
	if _, _, _, err := scanTracked(root, func(string) ([]byte, error) { return nil, sentinel }); !errors.Is(err, sentinel) {
		t.Fatalf("read error swallowed: %v", err)
	}
	fixtureWrite(t, root, "valid.go", "package ???")
	if _, _, _, err := scanTracked(root, os.ReadFile); err == nil {
		t.Fatal("parse error swallowed")
	}
}

func TestScanTrackedRefusesEmptyAndSleepSuppression(t *testing.T) {
	root := fixtureGit(t)
	if _, _, _, err := scanTracked(root, os.ReadFile); err == nil {
		t.Fatal("empty inventory accepted")
	}
	source := "package p\nimport \"time\"\nfunc TestBad(){\n//lint:allow test-fixed-sleep -- a reason cannot authorize debt\ntime.Sleep(time.Second)\n}\n"
	fixtureWrite(t, root, "bad_test.go", source)
	fixtureCommit(t, root)
	if _, _, _, err := scanTracked(root, os.ReadFile); err == nil || !strings.Contains(err.Error(), "bypasses") {
		t.Fatalf("suppression bypass accepted: %v", err)
	}
}

func TestScanTrackedOneReadAtNAnd2N(t *testing.T) {
	for _, n := range []int{8, 16} {
		t.Run(fmt.Sprint(n), func(t *testing.T) {
			root := fixtureGit(t)
			for i := 0; i < n; i++ {
				fixtureWrite(t, root, fmt.Sprintf("p%d.go", i), "package p\n")
			}
			fixtureCommit(t, root)
			reads := 0
			_, _, count, err := scanTracked(root, func(name string) ([]byte, error) { reads++; return os.ReadFile(name) })
			if err != nil || count != n || reads != n {
				t.Fatalf("count=%d reads=%d err=%v", count, reads, err)
			}
		})
	}
}

func TestDebtBaselineRealHistory(t *testing.T) {
	site := SleepSite{Path: "x_test.go", Function: "TestA", Call: "time.Sleep(time.Second)", Ordinal: 1}
	debt := Debt{Version: 1, Sites: []SleepSite{site}}
	root := fixtureGit(t)
	data, _ := json.Marshal(debt)
	fixtureWrite(t, root, debtPath, string(data))
	fixtureCommit(t, root)
	if _, err := gitOutput(root, "switch", "-c", "candidate"); err != nil {
		t.Fatal(err)
	}
	fixtureWrite(t, root, debtPath, `{"version":1,"sites":[]}`)
	fixtureCommit(t, root)
	got, err := debtBaseline(root)
	if err != nil || !reflect.DeepEqual(got, debt) {
		t.Fatalf("candidate replaced main authority: %+v %v", got, err)
	}
	if _, err := gitOutput(root, "config", "branch.main.merge", "refs/heads/missing"); err != nil {
		t.Fatal(err)
	}
	if _, err := debtBaseline(root); err == nil {
		t.Fatal("missing main ref accepted")
	}
}

func TestDebtBaselineRefusesMalformedAndDeleted(t *testing.T) {
	for _, scenario := range []string{"malformed", "deleted", "absent-anchor"} {
		t.Run(scenario, func(t *testing.T) {
			root := fixtureGit(t)
			switch scenario {
			case "malformed":
				fixtureWrite(t, root, debtPath, `{"version":99,"sites":[]}`)
				fixtureCommit(t, root)
			case "deleted":
				fixtureWrite(t, root, debtPath, `{"version":1,"sites":[]}`)
				fixtureCommit(t, root)
				if err := os.Remove(filepath.Join(root, debtPath)); err != nil {
					t.Fatal(err)
				}
				fixtureCommit(t, root)
			default:
				fixtureWrite(t, root, "x.go", "package p\n")
				fixtureCommit(t, root)
			}
			if _, err := debtBaseline(root); err == nil {
				t.Fatal("invalid baseline accepted")
			}
		})
	}
}

func TestDebtSetOracle(t *testing.T) {
	// Enumerate all subset transitions over a small independent domain; compare
	// the implementation with bit arithmetic rather than a second set matcher.
	const domain = 5
	sites := make([]sleepAt, domain)
	findings := make([]locatedFinding, domain)
	for i := range sites {
		sites[i] = sleepAt{SleepSite{"x_test.go", fmt.Sprintf("Test%d", i), "time.Sleep(time.Second)", 1}, i + 1}
		findings[i] = locatedFinding{"x_test.go", golint.Finding{Line: i + 1, Rule: sleepRule}}
	}
	for before := 0; before < 1<<domain; before++ {
		for after := 0; after < 1<<domain; after++ {
			previous, current := Debt{Version: 1, Sites: []SleepSite{}}, Debt{Version: 1, Sites: []SleepSite{}}
			for i, s := range sites {
				if before&(1<<i) != 0 {
					previous.Sites = append(previous.Sites, s.Site)
				}
				if after&(1<<i) != 0 {
					current.Sites = append(current.Sites, s.Site)
				}
			}
			if got := checkShrink(previous, current) == nil; got != (after & ^before == 0) {
				t.Fatalf("transition %b -> %b admitted=%v", before, after, got)
			}
		}
	}
	for mask := 0; mask < 1<<domain; mask++ {
		debt := Debt{Version: 1, Sites: []SleepSite{}}
		expected := 0
		for i, s := range sites {
			if mask&(1<<i) != 0 {
				debt.Sites = append(debt.Sites, s.Site)
			} else {
				expected++
			}
		}
		nonSleep := locatedFinding{"x_test.go", golint.Finding{Line: 99, Rule: "tmp-literal"}}
		remaining, err := checkDebt(append(append([]locatedFinding(nil), findings...), nonSleep), sites, debt)
		if err != nil || len(remaining) != expected+1 || remaining[len(remaining)-1] != nonSleep {
			t.Fatalf("mask %b remaining=%v err=%v", mask, remaining, err)
		}
	}
}

func TestDebtBaselineDetachedRemoteMain(t *testing.T) {
	root := fixtureGit(t)
	fixtureWrite(t, root, debtPath, `{"version":1,"sites":[]}`)
	fixtureCommit(t, root)
	if _, err := gitOutput(root, "update-ref", "refs/remotes/upstream/main", "HEAD"); err != nil {
		t.Fatal(err)
	}
	if _, err := gitOutput(root, "config", "--remove-section", "branch.main"); err != nil {
		t.Fatal(err)
	}
	if _, err := gitOutput(root, "checkout", "--detach"); err != nil {
		t.Fatal(err)
	}
	got, err := debtBaseline(root)
	if err != nil || len(got.Sites) != 0 {
		t.Fatalf("detached checkout failed %+v %v", got, err)
	}
	if _, err := gitOutput(root, "update-ref", "refs/remotes/another/main", "HEAD"); err != nil {
		t.Fatal(err)
	}
	if _, err := debtBaseline(root); err == nil {
		t.Fatal("ambiguous remote main admitted")
	}
	if _, err := gitOutput(root, "update-ref", "-d", "refs/remotes/another/main"); err != nil {
		t.Fatal(err)
	}
	if _, err := gitOutput(root, "update-ref", "-d", "refs/remotes/upstream/main"); err != nil {
		t.Fatal(err)
	}
	if _, err := debtBaseline(root); err == nil {
		t.Fatal("missing remote main admitted")
	}
}
